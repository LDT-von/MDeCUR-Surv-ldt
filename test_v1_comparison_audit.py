"""Generated V1 archive audits; no training, features, RNA arrays or weights."""
import csv
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import numpy as np
from cancer_parity import dct_bin_edges, _json_float, dct_risk, parity_metrics
from scripts.audit_v1_comparison_predictions import audit_comparison, main, V1, MODELS
from scripts.audit_parity_saved_predictions import _sha256


class V1ComparisonAuditTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='generated_v1_audit_')
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.manifest, self.reference = self.root/'manifest.csv', self.root/'reference.csv'
        self.compare = self.root/'comparison'
        self.compare.mkdir()
        self.rows = [dict(patient_id=f'SYN_T{i}', split='train', time=t, event=1)
                     for i, t in enumerate([1., 12., 24., 40.])]+[
                     dict(patient_id=f'SYN_V{i}', split='val', time=t, event=1)
                     for i, t in enumerate([5., 15., 35.])]
        self.csv(self.manifest, [dict(r, wsi_pt='DO_NOT_OPEN.pt', rna_npy='DO_NOT_OPEN.npy') for r in self.rows])
        self.csv(self.reference, self.rows)
        self.train_t, self.val_t = np.array([1., 12., 24., 40.]), np.array([5., 15., 35.])
        self.edges = dct_bin_edges(self.train_t, np.ones(4), 4)
        self.settings = dict(patient_batch_size=8, epochs=30, endpoint='DSS', time_unit='months',
                             seed=3, n_bins=4, num_patches=4096, alpha_surv=.5)
        self.plan = {'protocol': V1, 'settings': self.settings,
            'manifest': str(self.manifest), 'survival_reference': str(self.reference),
            'inputs': {'file_sha256': {str(p): _sha256(p) for p in (self.manifest, self.reference)},
                       'bin_edges': [_json_float(x) for x in self.edges]},
            'source_sha256': {'cancer_parity': _sha256(Path(__file__).with_name('cancer_parity.py'))}}
        self.write(self.compare/'plan.json', self.plan)
        plan_sha = _sha256(self.compare/'plan.json')
        self.summary = {'plan_sha256': plan_sha, 'rows': []}
        self.reports = {}
        best = np.array([[.2, .1, .05, .01], [.6, .4, .2, .1], [.95, .9, .8, .7]])
        for model, epoch in zip(MODELS, (8, 20)):
            directory = self.compare/model
            directory.mkdir()
            metrics = {}
            for selection, survival in (('best', best), ('last', best[::-1])):
                metrics[selection] = parity_metrics(self.train_t, np.ones(4), self.val_t, np.ones(3), survival, self.edges)
                metrics[selection]['validation_nll'] = .8 if selection == 'best' else .9
                predictions = [dict(patient_id=f'SYN_V{i}', risk=float(risk), **{
                    f'survival_bin_{j}': float(value) for j, value in enumerate(row)})
                    for i, (risk, row) in enumerate(zip(dct_risk(survival), survival))]
                self.csv(directory/f'val_predictions_{selection}.csv', predictions)
                (directory/f'checkpoint_{selection}.pt').write_bytes(b'OPAQUE GENERATED BYTES, NOT A PICKLE')
                self.summary['rows'].append({'model': model, 'selection': selection,
                    'epoch': epoch if selection == 'best' else 30,
                    'Harrell_C': metrics[selection]['c_index'], 'IPCW_C': metrics[selection]['c_index_ipcw'],
                    'NLL': metrics[selection]['validation_nll'], 'Brier': metrics[selection]['brier'],
                    'IBS_legacy_grid': metrics[selection]['ibs'], 'AUC_legacy_times': metrics[selection]['iauc'],
                    'metric_times': metrics[selection]['metric_times']})
            history = [{'epoch': i, 'c_index': 1. if i == epoch else (0. if i == 30 else .5),
                        'validation_nll': .8 if i == epoch else .9} for i in range(1, 31)]
            report = {'protocol': V1, 'model_id': model, 'settings': self.settings,
                'source_sha256': self.plan['source_sha256'], 'plan_sha256': plan_sha,
                'bin_edges': self.plan['inputs']['bin_edges'], 'epochs_completed': 30,
                'smoke_only': False, 'test_evaluated': False, 'patients': {'train': 4, 'val': 3},
                'events': {'train': 4, 'val': 3}, 'history': history, 'best_epoch': epoch, 'last_epoch': 30,
                'training_sampling_sha256': 'a'*64, 'best_validation': metrics['best'], 'last_validation': metrics['last']}
            self.reports[model] = report
            self.write(directory/'report.json', report)
        self.write(self.compare/'comparison.json', self.summary)

    @staticmethod
    def write(path, value):
        path.write_text(json.dumps(value, allow_nan=False), encoding='utf-8')

    @staticmethod
    def csv(path, rows):
        with path.open('w', newline='', encoding='utf-8') as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)

    def audit(self):
        return audit_comparison(self.manifest, self.reference, self.compare)

    def assert_audit_failed(self, fragment):
        result = self.audit()
        self.assertEqual(result['status'], 'failed')
        self.assertTrue(any(fragment in x for x in result['errors']), result['errors'])

    def change_report(self, model, callback):
        callback(self.reports[model])
        self.write(self.compare/model/'report.json', self.reports[model])

    def test_all_four_predictions_rescore_without_loading_weights_or_features(self):
        with patch('torch.load', side_effect=AssertionError('must not unpickle')):
            result = self.audit()
        self.assertEqual(result['status'], 'passed', result['errors'])
        self.assertEqual(len(result['rows']), 4)
        self.assertEqual(result['input_sha256'], result['input_sha256_after'])
        self.assertTrue(result['legacy_scorer_bytes_match_plan'])
        self.assertEqual(result['rows'][0]['finite_edge_audit']['survival_column_indices'], [0, 1, 2])
        self.assertNotIn('SYN_V', json.dumps(result))

    def test_wrong_risk_is_rejected(self):
        path = self.compare/MODELS[0]/'val_predictions_best.csv'
        with path.open() as handle:
            rows = list(csv.DictReader(handle))
        rows[0]['risk'] = '100'
        self.csv(path, rows)
        self.assert_audit_failed('stored risk')

    def test_duplicate_prediction_is_rejected(self):
        path = self.compare/MODELS[0]/'val_predictions_best.csv'
        with path.open() as handle:
            rows = list(csv.DictReader(handle))
        self.csv(path, rows+[rows[0]])
        self.assert_audit_failed('duplicate patient')

    def test_reported_c_cannot_replace_saved_prediction_score(self):
        self.change_report(MODELS[0], lambda r: r['best_validation'].update(c_index=.7))
        self.assert_audit_failed('reproduce c_index')

    def test_different_sampling_is_rejected(self):
        self.change_report(MODELS[1], lambda r: r.update(training_sampling_sha256='b'*64))
        self.assert_audit_failed('training-sampling')

    def test_nll_is_checked_against_same_epoch_and_not_fabricated_from_survival(self):
        self.change_report(MODELS[0], lambda r: r['history'][7].update(validation_nll=9.))
        self.assert_audit_failed('NLL differs')

    def test_summary_must_match_reports(self):
        self.summary['rows'][0]['Harrell_C'] = .123
        self.write(self.compare/'comparison.json', self.summary)
        self.assert_audit_failed('Summary/report')

    def test_cli_writes_new_result_and_preserves_existing_output(self):
        out = self.root/'audit.json'
        argv = ['--manifest', str(self.manifest), '--survival-reference', str(self.reference),
                '--comparison-root', str(self.compare), '--out', str(out)]
        self.assertEqual(main(argv), 0)
        before = out.read_bytes()
        with self.assertRaises(FileExistsError):
            main(argv)
        self.assertEqual(out.read_bytes(), before)


if __name__ == '__main__':
    unittest.main()
